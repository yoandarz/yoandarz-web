function getYouTubeId(url) {
  try {
    const parsedUrl = new URL(url);

    if (parsedUrl.hostname.includes("youtu.be")) {
      return parsedUrl.pathname.replace("/", "");
    }

    if (parsedUrl.pathname.includes("/shorts/")) {
      return parsedUrl.pathname.split("/shorts/")[1].split("/")[0];
    }

    return parsedUrl.searchParams.get("v");
  } catch (error) {
    return "";
  }
}

function createWhatsAppUrl() {
  const encodedMessage = encodeURIComponent(EVENTS_CONFIG.whatsappMessage);
  return `https://wa.me/${EVENTS_CONFIG.whatsappNumber}?text=${encodedMessage}`;
}

function setLink(selector, url) {
  const element = document.querySelector(selector);

  if (!element || !url) {
    return;
  }

  element.href = url;
  element.target = "_blank";
  element.rel = "noopener noreferrer";
}

function setupContactLinks() {
  setLink("[data-form-link]", EVENTS_CONFIG.formUrl);
  setLink("[data-whatsapp-link]", createWhatsAppUrl());
  setLink("[data-telegram-link]", EVENTS_CONFIG.telegramUrl);

  Object.entries(EVENTS_CONFIG.social).forEach(([key, url]) => {
    setLink(`[data-social="${key}"]`, url);
  });
}

function renderVideos() {
  const container = document.querySelector("[data-videos]");

  if (!container) {
    return;
  }

  container.innerHTML = "";

  EVENTS_CONFIG.videos.forEach((video) => {
    const videoId = getYouTubeId(video.url);
    const thumbnailUrl = videoId
      ? `https://img.youtube.com/vi/${videoId}/hqdefault.jpg`
      : "";

    const card = document.createElement("article");
    card.className = "video-card";

    const link = document.createElement("a");
    link.href = video.url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";

    const thumb = document.createElement("div");
    thumb.className = "video-thumb";

    if (thumbnailUrl) {
      const image = document.createElement("img");
      image.src = thumbnailUrl;
      image.alt = video.title;
      thumb.appendChild(image);
    }

    const title = document.createElement("span");
    title.className = "video-title";
    title.textContent = video.title;

    link.appendChild(thumb);
    link.appendChild(title);
    card.appendChild(link);
    container.appendChild(card);
  });
}

function renderConditions() {
  const container = document.querySelector("[data-conditions]");

  if (!container) {
    return;
  }

  container.innerHTML = "";

  EVENTS_CONFIG.conditions.forEach((condition) => {
    const details = document.createElement("details");
    details.className = "condition-item";

    const summary = document.createElement("summary");
    summary.textContent = condition.title;

    const paragraph = document.createElement("p");
    paragraph.textContent = condition.text;

    details.appendChild(summary);
    details.appendChild(paragraph);
    container.appendChild(details);
  });
}

function setupMobileMenu() {
  const button = document.querySelector("[data-menu-button]");
  const nav = document.querySelector("[data-main-nav]");

  if (!button || !nav) {
    return;
  }

  button.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("is-open");
    button.setAttribute("aria-expanded", String(isOpen));
    button.textContent = isOpen ? "Cerrar" : "Menú";
    document.body.classList.toggle("menu-open", isOpen);
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("is-open");
      button.setAttribute("aria-expanded", "false");
      button.textContent = "Menú";
      document.body.classList.remove("menu-open");
    });
  });
}

function initEventsPage() {
  setupContactLinks();
  renderVideos();
  renderConditions();
  setupMobileMenu();
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initEventsPage);
} else {
  initEventsPage();
}